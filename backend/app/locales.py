def pack(code: str | None) -> dict[str, Any]:
    """Return a complete pack: the locale's entries merged over English.

    Missing top-level keys come from English; the nested `safety` and `keywords`
    maps merge key by key, so a translator who adds one safety line still gets
    the rest.
    """
    base = dict(EN)
    cur = PACKS.get(normalise(code)) or EN
    for key, value in cur.items():
        if key in ("safety", "keywords") and isinstance(value, dict):
            merged = dict(EN[key])
            if cur is not EN:
                merged.update(value)
            base[key] = merged
        else:
            base[key] = value
    # Voice lines live in their own table so adding a language to calls does not
    # mean touching every phrase set above.
    base.update(VOICE_EN)
    base.update(VOICE.get(normalise(code)) or {})
    return base

