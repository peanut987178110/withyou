"""Locale packs for the mock reply engine.

The production build sends the user's language to the hosted model. This module
is the documented `WITHYOU_AI_MODE=mock` counterpart: for each supported UI
locale it supplies (a) the phrase set the deterministic composer draws from and
(b) the keyword lists used for intent detection, because the English keyword
lists match nothing when the user writes 中文 or العربية.

Safety strings live here too: S001–S003 and the crisis tail have to reach the
user in the language of the app, and the review queue still sees the canonical
English `category` from `classify()`.

A locale may omit any key; `pack()` shallow-merges it over English so a partial
translation degrades to English instead of raising KeyError mid-generation.
"""
from __future__ import annotations

from typing import Any

SUPPORTED = ["en", "zh", "zh-TW", "ja", "ko", "es", "fr", "de", "pt", "ar"]


def normalise(code: str | None) -> str:
    """Map a stored/account locale onto one of SUPPORTED."""
    tag = str(code or "").replace("_", "-")
    if tag in SUPPORTED:
        return tag
    low = tag.lower()
    if low.startswith("zh"):
        return "zh-TW" if any(x in low for x in ("hant", "tw", "hk", "mo")) else "zh"
    base = low.split("-")[0]
    return base if base in SUPPORTED else "en"


